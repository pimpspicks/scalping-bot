"""Export a trained logistic-regression model on the `tv` feature set as a TradingView Pine Script
strategy. The script recomputes the same features from the chart's bars, applies the exported
coefficients, plots the probability edge, backtests in TradingView's strategy tester, and fires
alerts (usable as webhooks).

Feature definitions here must match features.tv_symbol_features exactly.
"""
import math

import numpy as np

from .features import TV_RET_LAGS

TV_TICKERS = {
    "phemex": "PHEMEX:{s}USDT.P",  # USDT perpetual
    "binance": "BINANCE:{s}USDT",
    "binanceus": "BINANCEUS:{s}USDT",
    "coinbase": "COINBASE:{s}USD",
}

_OWN_FEATURES = {
    **{f"ret_{k}": f"math.log(close / close[{k}])" for k in TV_RET_LAGS},
    "vol_12": "ta.stdev(r1, 12)",
    "vol_60": "ta.stdev(r1, 60)",
    "range_1": "math.log(high / low)",
    "volume_z": "(lv - ta.sma(lv, 60)) / ta.stdev(lv, 60)",
    "vwap_dev": "math.log(close / (math.sum(hlc3 * volume, 12) / math.sum(volume, 12)))",
}


def linear_params(bundle: dict) -> tuple[float, list[tuple[str, float, float, float, float]]]:
    """Collapse imputer + scaler + logistic regression into (intercept, [(feature, weight, mean, scale, fill)])."""
    pipe = bundle["model"]
    steps = dict(pipe.named_steps)
    if "logisticregression" not in steps:
        raise SystemExit("Pine export needs a logreg model (train with --model logreg)")
    imp, sc, lr = steps["simpleimputer"], steps["standardscaler"], steps["logisticregression"]
    rows = list(zip(bundle["features"], lr.coef_[0], sc.mean_, sc.scale_, imp.statistics_))
    return float(lr.intercept_[0]), [(f, float(w), float(m), float(s), float(fill)) for f, w, m, s, fill in rows]


def predict_like_pine(bundle: dict, x: dict[str, float]) -> float:
    """The exact arithmetic the generated script does; used by tests to check the export."""
    b, rows = linear_params(bundle)
    z = b + sum(w * ((fill if x.get(f) is None or np.isnan(x[f]) else x[f]) - m) / s for f, w, m, s, fill in rows)
    return 1 / (1 + math.exp(-z))


def _num(v: float) -> str:
    return repr(float(v))


